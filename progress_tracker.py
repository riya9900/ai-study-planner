import re
from typing import List, Dict, Any
import streamlit as st

def parse_study_plan_tasks(plan_markdown: str, schedule_data: Dict[str, Any] = None) -> List[Dict[str, Any]]:
    """Extracts actionable study tasks and topics from the generated study plan markdown.
    Includes tiered fallbacks to ensure a reliable, non-empty task list is always generated.

    Args:
        plan_markdown: The markdown text generated by the AI agent.
        schedule_data: Raw schedule dictionary from calculate_study_schedule.

    Returns:
        A list of task dicts with id, day_num, day_title, category, icon, and text.
    """
    tasks: List[Dict[str, Any]] = []
    if not plan_markdown:
        return tasks

    # Pattern to match day headers like '### 📍 DAY 1 — ...' or '### DAY 2: ...'
    day_pattern = re.compile(
        r'(?:^|\n)\s*#{1,4}\s*(?:📍\s*)?(?:\*\*)?DAY\s*(\d+)[:\s—\-]+([^\n*#]+)(?:\*\*)?',
        re.IGNORECASE
    )
    
    matches = list(day_pattern.finditer(plan_markdown))
    
    if matches:
        for i, match in enumerate(matches):
            day_num = int(match.group(1))
            raw_title = match.group(2).strip().strip('*').strip()
            # Clean off any trailing markdown formatting
            day_title = re.sub(r'[:—\-]+$', '', raw_title).strip()
            
            start_pos = match.end()
            end_pos = matches[i + 1].start() if i + 1 < len(matches) else len(plan_markdown)
            day_content = plan_markdown[start_pos:end_pos]
            
            # Sub-sections
            learn_text = ''
            practice_text = ''
            goal_text = ''
            
            # Match Learn block
            learn_m = re.search(
                r'(?:📖\s*)?\*\*(?:Learn|Core Topics|Study):\*\*(.*?)(?=(?:📝\s*)?\*\*Practice|\*\*Today\'s Goal|---|#{1,4}\s*DAY|\Z)',
                day_content, re.DOTALL | re.IGNORECASE
            )
            if learn_m:
                learn_text = learn_m.group(1).strip()
                
            # Match Practice block
            practice_m = re.search(
                r'(?:📝\s*)?\*\*(?:Practice|Tasks|Action Items):\*\*(.*?)(?=(?:🎯\s*)?\*\*Today\'s Goal|---|#{1,4}\s*DAY|\Z)',
                day_content, re.DOTALL | re.IGNORECASE
            )
            if practice_m:
                practice_text = practice_m.group(1).strip()
                
            # Match Today's Goal block
            goal_m = re.search(
                r'(?:🎯\s*)?\*\*(?:Today\'s Goal|Daily Goal|Goal):\*\*(.*?)(?=---|#{1,4}\s*DAY|\Z)',
                day_content, re.DOTALL | re.IGNORECASE
            )
            if goal_m:
                goal_text = goal_m.group(1).strip()

            day_tasks: List[Dict[str, Any]] = []
            
            # Helper to extract bullet items
            def extract_bullets(block_text: str, category: str, icon: str):
                extracted = []
                b_idx = 1
                for line in block_text.splitlines():
                    clean_line = line.strip()
                    if clean_line.startswith(('•', '-', '*', '1.', '2.', '3.', '4.', '5.')):
                        item = re.sub(r'^[•\-\*]|\d+\.\s*', '', clean_line).strip()
                        if item and len(item) > 3:
                            extracted.append({
                                'id': f'd{day_num}_{category.lower()}_{b_idx}',
                                'day_num': day_num,
                                'day_title': f'Day {day_num}: {day_title}',
                                'category': category,
                                'icon': icon,
                                'text': item
                            })
                            b_idx += 1
                return extracted

            learn_items = extract_bullets(learn_text, 'Learn', '📖')
            practice_items = extract_bullets(practice_text, 'Practice', '📝')
            day_tasks.extend(learn_items)
            day_tasks.extend(practice_items)

            # Add today's goal as a synthesis task if available
            if goal_text:
                first_line = goal_text.splitlines()[0].strip().strip('*')
                if len(first_line) > 5:
                    day_tasks.append({
                        'id': f'd{day_num}_goal',
                        'day_num': day_num,
                        'day_title': f'Day {day_num}: {day_title}',
                        'category': 'Goal',
                        'icon': '🎯',
                        'text': f'Mastery Check: {first_line}'
                    })

            # Fallback if no sub-bullets found for this day
            if not day_tasks:
                day_tasks.append({
                    'id': f'd{day_num}_focus',
                    'day_num': day_num,
                    'day_title': f'Day {day_num}: {day_title}',
                    'category': 'Day Focus',
                    'icon': '📍',
                    'text': f'Complete daily session: {day_title}'
                })
                
            tasks.extend(day_tasks)

    # Secondary fallback: use schedule_data daily_calendar if no day headers matched
    if not tasks and schedule_data and 'daily_calendar' in schedule_data:
        for d in schedule_data['daily_calendar']:
            day_n = d.get('day_number', 1)
            fmt_date = d.get('formatted_date', '')
            is_buf = d.get('is_buffer', False)
            title = 'Buffer & Revision Session' if is_buf else f'Day {day_n} Study Session'
            hrs = d.get('hours', 0)
            tasks.append({
                'id': f'd{day_n}_cal',
                'day_num': day_n,
                'day_title': f'Day {day_n} ({fmt_date})',
                'category': 'Buffer' if is_buf else 'Study Session',
                'icon': '🔄' if is_buf else '📖',
                'text': f'{title} ({hrs} hrs)'
            })

    return tasks


def render_study_progress_tracker(tasks: List[Dict[str, Any]]):
    """Renders the Study Progress Tracker UI component in Streamlit.
    Displays percentage, progress bar, counts, and interactive checkboxes.
    """
    st.markdown("### 📊 Study Progress")
    
    if not tasks:
        st.info("No study tasks found to track. Generate a study plan to start tracking progress.")
        return

    # Ensure all task keys exist in session_state
    for t in tasks:
        key = f"task_{t['id']}"
        if key not in st.session_state:
            st.session_state[key] = False

    # Calculate current progress stats
    total_tasks = len(tasks)
    completed_tasks = sum(1 for t in tasks if st.session_state.get(f"task_{t['id']}", False))
    remaining_tasks = max(0, total_tasks - completed_tasks)
    progress_pct = int(round((completed_tasks / total_tasks) * 100)) if total_tasks > 0 else 0
    progress_ratio = (completed_tasks / total_tasks) if total_tasks > 0 else 0.0

    # 1. Stat cards in 4 columns
    c1, c2, c3, c4 = st.columns(4)
    with c1:
        st.metric("Overall Progress", f"{progress_pct}%")
    with c2:
        st.metric("Completed Tasks", f"{completed_tasks} / {total_tasks}")
    with c3:
        st.metric("Remaining Tasks", f"{remaining_tasks}")
    with c4:
        if progress_pct == 100:
            status_text = "🎉 All Done!"
        elif progress_pct >= 50:
            status_text = "🔥 Over Halfway"
        elif progress_pct > 0:
            status_text = "🚀 In Progress"
        else:
            status_text = "⏳ Ready to Start"
        st.metric("Current Status", status_text)

    # 2. Progress Bar
    st.progress(progress_ratio)

    # 3. Quick action buttons
    btn_col1, btn_col2, _ = st.columns([1.2, 1.2, 3])
    with btn_col1:
        if st.button("✅ Mark All Complete", key="btn_mark_all_tasks", help="Mark all tasks as completed"):
            for t in tasks:
                st.session_state[f"task_{t['id']}"] = True
            st.rerun()
    with btn_col2:
        if st.button("🔄 Reset Progress", key="btn_reset_all_tasks", help="Reset all completed tasks to 0%"):
            for t in tasks:
                st.session_state[f"task_{t['id']}"] = False
            st.rerun()

    # 4. Interactive Checklist grouped by Day
    st.markdown("#### 📝 Interactive Task Checklist")
    st.caption("Check off topics and practice exercises as you complete them. Your progress updates immediately.")

    days_dict: Dict[int, List[Dict[str, Any]]] = {}
    for t in tasks:
        d_num = t.get("day_num", 1)
        days_dict.setdefault(d_num, []).append(t)

    for d_num, d_tasks in days_dict.items():
        d_completed = sum(1 for t in d_tasks if st.session_state.get(f"task_{t['id']}", False))
        d_total = len(d_tasks)
        d_title = d_tasks[0].get("day_title", f"Day {d_num}")
        is_all_done = (d_completed == d_total and d_total > 0)
        
        status_icon = "✅" if is_all_done else "📍"
        badge = "COMPLETED" if is_all_done else f"{d_completed}/{d_total} Done"
        expander_title = f"{status_icon} {d_title} &nbsp;·&nbsp; ({badge})"
        
        # Keep day expanded if incomplete or if only a few days
        is_expanded = (not is_all_done) or (len(days_dict) <= 3)
        with st.expander(expander_title, expanded=is_expanded):
            for t in d_tasks:
                key = f"task_{t['id']}"
                checked = st.session_state.get(key, False)
                category_badge = f"**[{t['category']}]**"
                if checked:
                    label = f"~~{t['icon']} {category_badge} {t['text']}~~"
                else:
                    label = f"{t['icon']} {category_badge} {t['text']}"
                
                st.checkbox(label, key=key)
